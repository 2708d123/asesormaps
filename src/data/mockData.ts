export function getAdvisor(advisorId: string) {
  return advisors.find((advisor) => advisor.id === advisorId)
}

export function getProperty(slug: string) {
  return properties.find((property) => property.slug === slug)
}

export function filterProperties(
  list: Property[],
  filters: PropertyFiltersState,
  sortBy = 'recent',
) {
  const query = filters.query.trim().toLowerCase()
  const result = list.filter((property) => {
    const advisor = getAdvisor(property.advisorId)
    const matchesQuery =
      !query ||
      [property.title, property.neighborhood, property.city, property.propertyType, advisor?.displayName]
        .filter(Boolean)
        .join(' ')
        .toLowerCase()
        .includes(query)

    return (
      property.status === 'active' &&
      matchesQuery &&
      (filters.operationType === 'todas' || property.operationType === filters.operationType) &&
      (filters.propertyType === 'Todos' || property.propertyType === filters.propertyType) &&
      (!filters.minPrice || property.price >= Number(filters.minPrice)) &&
      (!filters.maxPrice || property.price <= Number(filters.maxPrice)) &&
      (filters.city === 'Todas' || property.city === filters.city) &&
      (filters.neighborhood === 'Todas' || property.neighborhood === filters.neighborhood) &&
      (filters.zone === 'Todas' || property.zone === filters.zone) &&
      (!filters.minBedrooms || (property.bedrooms ?? 0) >= Number(filters.minBedrooms)) &&
      (!filters.minBathrooms || (property.bathrooms ?? 0) >= Number(filters.minBathrooms)) &&
      (!filters.minLandM2 || (property.landM2 ?? 0) >= Number(filters.minLandM2)) &&
      (!filters.minConstructionM2 || (property.constructionM2 ?? 0) >= Number(filters.minConstructionM2)) &&
      (!filters.verifiedOnly || Boolean(advisor?.verified)) &&
      (!filters.featuredOnly || property.isFeatured)
    )
  })

  return [...result].sort((a, b) => {
    if (sortBy === 'price-asc') return a.price - b.price
    if (sortBy === 'price-desc') return b.price - a.price
    if (sortBy === 'land-desc') return (b.landM2 ?? 0) - (a.landM2 ?? 0)
    if (sortBy === 'bedrooms-desc') return (b.bedrooms ?? 0) - (a.bedrooms ?? 0)
    return new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime()
  })
}
